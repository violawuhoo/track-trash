/**
 * 解锁条件是否满足（只看条件，不看载体）。
 *
 * 注意 `stage` 的口径：GDD §6.2 写「完成阶段 2」，此时 `progress.stage` 已变成 3，
 * 所以条件写成 `stage: 3`（而不是 2）。
 */
export function logUnlocked(log: LogDoc, state: LogProgress): boolean {
  const u = log.unlock;
  if (u.day !== undefined && state.day < u.day) return false;
  if (u.crafts !== undefined && state.crafts < u.crafts) return false;
  if (u.stage !== undefined && state.stage < u.stage) return false;
  if (u.buildDone && !state.buildDone) return false;
  return true;
}

/** 载体是否已获得（合成过就算，物品被消耗掉也不收回） */
export function carrierFound(log: LogDoc, state: LogProgress): boolean {
  return state.logsFound.includes(log.id);
}

