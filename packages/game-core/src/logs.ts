/**
 * 前任日志（C 线 · C1 批次）。
 *
 * 8 篇前任机修陈九的私人记录。**正文一字不改地来自 GDD §6.3「碎片全文」**，
 * 这里只做两件事：
 * 1. 把 GDD 的 Markdown 引用块（`>` 前缀）拆成段落数组 —— UI 按段落渲染。
 * 2. 保留 `**粗体**` 标记（UI 端渲染成 <strong>），所以正文与 GDD 逐字一致。
 *
 * ## 设计口径（GDD §6.1 / §6.2 / §6.4）
 *
 * | 项 | 结论 |
 * |---|---|
 * | 载体形态 | 复用既有 kind `accident`，不新增 kind 枚举 |
 * | 载体获取 | 靠合成（8 条精确配方），不新增可捡来源 |
 * | 内容位置 | 独立的日志面板（UI 层），不进 `items.ts` 的 `desc` |
 * | 解锁条件 | 挂在**日志条目的可见性**上：`unlock` 字段（天数 / 合成次数 / 阶段 / 建设期完成） |
 *
 * ⚠️ **可见性 = 解锁条件满足 + 载体已获得**。
 * GDD §6.2 原文说解锁条件「不挂在物品获取上」，但那一句讨论的是
 * 「解锁条件不作为**获取载体**的门槛」——载体是普通合成产物，谁都能合。
 * 玩家侧的语义则是「合出载体 = 拿到了那段记录」（任务书口径：
 * 「玩家能读到已合出的日志」）。所以这里取**两个条件都要满足**：
 * 条件没到（还没到那个时间点 / 还没走完那个阶段）→ 读不了；
 * 载体没合出来 → 也读不了。
 *
 * 载体已获得这一半记在存档的 `logsFound`（日志 id 集合）里，
 * 由 `state.ts` 的 `craft()` 在产出载体时写入（去重）。
 *
 * ## 载体 ↔ 日志映射（8 ↔ 8，必须一条不落）
 *
 * | 日志 | 载体物品 | 精确配方 | 前任记录日 | 解锁条件 |
 * |---|---|---|---|---|
 * | L1 缺页手稿   | `log_page1`  | `manual` + `photo`    | 第 1–6 天  | 天数 ≥ 5 且 合成次数 ≥ 3 |
 * | L2 燃料清单   | `log_map2`   | `lamp` + `lottery`    | 第 7 天    | 天数 ≥ 9 |
 * | L3 值班记录   | `log_page2`  | `manual` + `broom`    | 第 8–11 天 | 天数 ≥ 12 |
 * | L4 航路草图   | `log_map1`   | `manual` + `mirror`   | 第 12 天   | 完成阶段 2 |
 * | L5 存储芯片   | `log_chip1`  | `homework` + `switchpanel` | 第 14 天 | 合成次数 ≥ 14 |
 * | L6 未完的问句 | `log_q1`     | `hourglass` + `poker` | 第 18 天   | 天数 ≥ 18 |
 * | L7 前任遗物   | `log_b1`     | `warnlamp` + `crystal`| 第 20 天   | 天数 ≥ 20 |
 * | L8 数据卷盘   | `log_reel1`  | `generator` + `note`  | 第 21 天   | 完成阶段 3 的 `s3-3` |
 */

/**
 * 日志解锁判定需要的最小状态面。
 *
 * 刻意**不收整个 `SaveState`**：web 端的 `SaveStateV2` 是 core `SaveState`
 * 的 `Omit` 版本（去掉了 `scene` / `areaId`），直接把 `SaveState` 当参数会让
 * web 侧需要一次类型断言。收窄到这几个字段后，core 的 `SaveState` 与 web 的
 * `SaveStateV2` **结构上同时满足**，两边都能直接传。
 */
export interface LogProgress {
  /** 存档天数 */
  day: number;
  /** 累计合成次数 */
  crafts: number;
  /** 当前阶段 */
  stage: 1 | 2 | 3 | 4;
  /** 建设期三步是否走满 */
  buildDone: boolean;
  /** 已获得的日志 id 集合（**本周目**） */
  logsFound: string[];
  /**
   * 跨周目的已读日志 id 集合（`ngPlus.readLogs`，C2 批次）。
   *
   * 可选：web 端传 `save.ngPlus.readLogs`。不传就退化成「只看本周目」的老行为。
   *
   * 语义差异（别混淆）：
   * - `logsFound` = **本周目**合出过哪些载体（`craft()` 时记，会被清零）
   * - `readLogs`  = **这辈子**读过哪些篇目（跨周目保留）
   *
   * GDD §7.1 G1：已读篇目在二周目**不再重复给解锁演出** —— 读过就记得。
   */
  readLogs?: string[];
}

/** 一篇前任日志 */
export interface LogDoc {
  /** 日志 id（L1–L8）。与 `SaveState.logsFound` 里的 id 一致 */
  id: string;
  /** 标题（= 载体物品名） */
  title: string;
  /** 载体物品 id。合成它才算「拿到这段记录」 */
  carrierId: string;
  /** 前任记录日。给玩家看的时间锚点 */
  recordDay: string;
  /** 解锁条件。字段为空表示无附加条件 */
  unlock: {
    /** 存档天数 ≥ 此值 */
    day?: number;
    /** 累计合成次数 ≥ 此值 */
    crafts?: number;
    /** 阶段 ≥ 此值（GDD 的「完成阶段 N」= stage 变成 N+1） */
    stage?: number;
    /** 建设期三步是否走满（GDD 的「完成阶段 3 的 s3-3」） */
    buildDone?: boolean;
  };
  /** 给玩家看的解锁提示（面板里未解锁时显示） */
  unlockHint: string;
  /**
   * 玩家视角的一句提示（GDD §6.2「玩家视角」列）。
   * 未解锁时用它替代标题 —— 告诉玩家「你可能会撞见什么」，但不剧透具体是什么。
   */
  playerView: string;
  /**
   * 拼合点（GDD §6.4）：读到这一篇时合并出的那条新结论。
   *
   * 只有 **L4 / L6 / L8** 有 —— 第 8 篇不给「前任后来怎样」的答案。
   *
   * ⚠️ **L2 没有拼合点**（GDD §6.4 的拼合点判定，P1 已取消）：
   * 拼合点必须**跨篇**（结论不能被任一单篇独立支撑）且**有增量**
   * （读到本篇之前玩家无法完整说出这条结论）。
   * 原来的 L2 拼合点「船上原本有两个人，其中一个后来自己走了」
   * 两端都在 **L1 之内**（「船上原本两个人。我在这儿。」/
   * 「如果你读到这段，说明我是那个没走的。」），
   * 而 L2 是**燃料消耗表**、不提供任何相关新信息 ——
   * 所以它是**复述**而不是揭示，不构成拼合点。已删除。
   */
  puzzle?: string;
  /** 正文段落。段内 `**` 是粗体标记，UI 端渲染成 <strong> */
  paragraphs: string[];
}

